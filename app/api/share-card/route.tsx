import { ImageResponse } from "next/og";
import { getAqiBand } from "@/lib/aqi";

export const size = { width: 1200, height: 630 };
export const contentType = "image/png";

/**
 * GET /api/share-card?city=..&aqi=..&language=..
 * Generates the shareable "Family Air Card" PNG for Community Mode using
 * Next's built-in `next/og` ImageResponse (Satori), so no native `canvas`
 * binary is needed on the server. Only non-sensitive query values (city
 * name, AQI number, language) are accepted -- never profile/health data.
 */
export async function GET(request: Request) {
  const { searchParams } = new URL(request.url);
  const city = (searchParams.get("city") ?? "Your neighborhood").slice(0, 60);
  const usAqi = Math.max(0, Math.min(500, Number(searchParams.get("aqi")) || 0));
  const band = getAqiBand(usAqi);

  return new ImageResponse(
    (
      <div
        style={{
          width: "100%",
          height: "100%",
          display: "flex",
          flexDirection: "column",
          justifyContent: "space-between",
          background: "#0f172a",
          padding: "56px",
          fontFamily: "sans-serif",
          color: "#f8fafc",
        }}
      >
        <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between" }}>
          <div style={{ display: "flex", fontSize: 40, fontWeight: 700 }}>Saans</div>
          <div style={{ display: "flex", fontSize: 24, opacity: 0.8 }}>Family Air Card</div>
        </div>

        <div style={{ display: "flex", flexDirection: "column" }}>
          <div style={{ display: "flex", fontSize: 32, opacity: 0.85 }}>{city}</div>
          <div style={{ display: "flex", alignItems: "baseline", gap: 24, marginTop: 12 }}>
            <div style={{ display: "flex", fontSize: 140, fontWeight: 800, lineHeight: 1 }}>{usAqi}</div>
            <div
              style={{
                display: "flex",
                fontSize: 30,
                fontWeight: 700,
                padding: "10px 24px",
                borderRadius: 999,
                background: band.bg,
                color: band.fg,
              }}
            >
              {band.label}
            </div>
          </div>
          <div style={{ display: "flex", fontSize: 24, marginTop: 20, maxWidth: 900, opacity: 0.9 }}>{band.summary}</div>
        </div>

        <div style={{ display: "flex", fontSize: 20, opacity: 0.7 }}>Data: Open-Meteo &middot; Generated by the Saans app</div>
      </div>
    ),
    { ...size }
  );
}
